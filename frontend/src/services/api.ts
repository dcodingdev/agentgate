import type {
  CreateRunRequest,
  CreateRunResponse,
  ResumeBody,
  ResumeRunResponse,
  RunStateResponse,
  StreamEventPayload,
} from '../types'

const API_BASE = '' // Uses Vite dev proxy to localhost:8000

export async function checkBackendHealth(): Promise<{ status: string; service: string; version: string }> {
  const res = await fetch(`${API_BASE}/health`)
  if (!res.ok) {
    throw new Error(`Health check failed with status ${res.status}`)
  }
  return res.json()
}

export async function createRun(payload: CreateRunRequest): Promise<CreateRunResponse> {
  const res = await fetch(`${API_BASE}/runs`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  })
  if (!res.ok) {
    const err = await res.json().catch(() => ({ detail: 'Failed to create run' }))
    throw new Error(err.detail || `Request failed with status ${res.status}`)
  }
  return res.json()
}

export async function getRunState(threadId: string): Promise<RunStateResponse> {
  const res = await fetch(`${API_BASE}/runs/${threadId}/state`)
  if (!res.ok) {
    const err = await res.json().catch(() => ({ detail: 'Failed to retrieve state' }))
    throw new Error(err.detail || `Failed with status ${res.status}`)
  }
  return res.json()
}

export async function resumeRun(threadId: string, body: ResumeBody): Promise<ResumeRunResponse> {
  const res = await fetch(`${API_BASE}/runs/${threadId}/resume`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  })
  if (!res.ok) {
    const err = await res.json().catch(() => ({ detail: 'Failed to resume run' }))
    throw new Error(err.detail || `Failed with status ${res.status}`)
  }
  return res.json()
}

export function subscribeToRunEvents(
  threadId: string,
  onEvent: (event: StreamEventPayload) => void,
  onClose?: () => void,
  onError?: (err: any) => void
): () => void {
  const url = `${API_BASE}/runs/${threadId}/stream`
  const eventSource = new EventSource(url)

  const handleEvent = (event: MessageEvent, eventType: string) => {
    try {
      const data = JSON.parse(event.data)
      onEvent({
        event: eventType,
        data,
        timestamp: new Date().toLocaleTimeString(),
      })
    } catch {
      onEvent({
        event: eventType,
        data: { raw: event.data },
        timestamp: new Date().toLocaleTimeString(),
      })
    }
  }

  // Standard SSE events generated by AgentService
  const eventTypes = [
    'status',
    'node_update',
    'hitl_paused',
    'completed',
    'rejected',
    'error',
    'done',
  ]

  eventTypes.forEach((type) => {
    eventSource.addEventListener(type, (e: MessageEvent) => {
      handleEvent(e, type)
      if (type === 'done' || type === 'error') {
        if (onClose) onClose()
        eventSource.close()
      }
    })
  })

  eventSource.onmessage = (e: MessageEvent) => {
    handleEvent(e, 'message')
  }

  eventSource.onerror = (err) => {
    if (onError) onError(err)
  }

  // Return unsubscribe cleanup function
  return () => {
    eventSource.close()
  }
}

